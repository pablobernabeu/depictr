#' and noise. The two series show the grouped [timeseries_plot()] on the
#' package's own data, and one series extracted as a monthly `ts` (frequency 12)
#' lets [decompose_plot()] and [acf_plot()] show the trend and seasonality.
#'
#' The data are synthetic, generated by `data-raw/generate_datasets.R` with a
#' fixed seed.
#'
#' @format A data frame with 144 rows and 3 variables:
#' \describe{
#'   \item{date}{First day of the month (`Date`), from January 2018.}
#'   \item{series}{Product line (factor): `indoor` or `outdoor`.}
#'   \item{sales}{Monthly sales (units).}
#' }
#' @source Simulated by `data-raw/generate_datasets.R` in the source repository.
"monthly_sales"
